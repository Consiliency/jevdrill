"""Regenerate pinned BAML output and derived boundary schemas; compare by default."""
import argparse
import ast
import copy
import hashlib
import importlib
import importlib.metadata
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

from pydantic import TypeAdapter

ROOT = Path(__file__).resolve().parents[1]


def normalize_artifact(blob, source_paths):
    # Pinned BAML artifact ABI 8: authenticated Borsh header plus program payload.
    if blob[:8] != b"BAMLART\0" or int.from_bytes(blob[8:12], "little") != 8:
        raise ValueError("unsupported BAML artifact format")
    end = 20 + int.from_bytes(blob[12:20], "little")
    header, payload = blob[20:end], blob[end:]
    fingerprint_size = int.from_bytes(header[:4], "little")
    if len(header) != 4 + fingerprint_size + 1 + 8 + 32:
        raise ValueError("invalid BAML artifact header")
    if header[4 + fingerprint_size] != 0:
        raise ValueError("expected BAML program artifact")
    if int.from_bytes(header[-40:-32], "little") != len(payload):
        raise ValueError("invalid BAML payload length")
    metadata = blob[8:12] + header[:-32]
    if hashlib.sha256(metadata + payload).digest() != header[-32:]:
        raise ValueError("BAML artifact checksum mismatch")
    for source in source_paths:
        portable = source.encode("utf-8")
        native = source.replace("/", "\\").encode("utf-8")
        # Only complete, length-prefixed, explicitly authored source filenames.
        prefix = len(portable).to_bytes(4, "little")
        payload = payload.replace(prefix + native, prefix + portable)
    return blob[:20] + header[:-32] + hashlib.sha256(metadata + payload).digest() + payload


def normalized_outputs(outputs):
    normalized = dict(outputs)
    bytecode_path = Path("_inlinedbaml.py")
    tree = ast.parse(outputs[bytecode_path].decode("utf-8"))
    assignments = [node for node in tree.body if isinstance(node, ast.AnnAssign)
                   and isinstance(node.target, ast.Name) and node.target.id == "BYTECODE"]
    if len(assignments) != 1:
        raise ValueError("unsupported generated bytecode declaration")
    assignment = assignments[0]
    sources = [p.relative_to(ROOT).as_posix() for p in (ROOT / "baml_src").rglob("*.baml")]
    assignment.value = ast.Constant(normalize_artifact(ast.literal_eval(assignment.value), sources))
    normalized[bytecode_path] = ast.dump(tree, include_attributes=False).encode("utf-8")
    source_path = Path("_baml_sources.py")
    source_tree = ast.parse(outputs[source_path].decode("utf-8"))
    source_assignment = next(node for node in source_tree.body if isinstance(node, ast.AnnAssign)
                             and isinstance(node.target, ast.Name) and node.target.id == "FILES")
    authored = {p.relative_to(ROOT / "baml_src").as_posix()
                for p in (ROOT / "baml_src").rglob("*.baml")}
    portable_names = {name.replace("/", "\\"): name for name in authored}
    source_files = ast.literal_eval(source_assignment.value)
    source_assignment.value = ast.Dict(
        keys=[ast.Constant(portable_names.get(name, name)) for name in source_files],
        values=[ast.Constant(content) for content in source_files.values()],
    )
    normalized[source_path] = ast.dump(source_tree, include_attributes=False).encode("utf-8")
    manifest_path = Path(".baml-generator-output.json")
    manifest = json.loads(outputs[manifest_path])
    for entry in manifest["files"]:
        path = Path(entry["relative_path"])
        if path not in outputs or hashlib.sha256(outputs[path]).hexdigest() != entry["sha256"]:
            raise ValueError("generated manifest checksum mismatch")
        entry["sha256"] = hashlib.sha256(normalized[path]).hexdigest()
    normalized[manifest_path] = json.dumps(manifest, sort_keys=True).encode("utf-8")
    return normalized


def schemas(module, metadata):
    found = set()
    results = {}
    for name in metadata["contracts"]:
        schema = TypeAdapter(getattr(module, name)).json_schema()
        definitions = dict(schema.get("$defs", {}))
        if "properties" in schema:
            definitions[name] = schema
        for class_name, definition in definitions.items():
            fields = definition.get("properties")
            if fields is None:
                continue
            definition["additionalProperties"] = False
            optional = metadata["omittable"].get(class_name, [])
            if not set(optional) <= fields.keys():
                raise ValueError(f"unknown omittable field: {class_name}")
            definition["required"] = sorted(set(fields) - set(optional))
            for field_name, field in fields.items():
                field.pop("default", None)
                path = f"{class_name}.{field_name}"
                found.add(path)
                if path in metadata["field_rules"]:
                    field.update(copy.deepcopy(metadata["field_rules"][path]))
                if path in metadata["identities"]:
                    field["pattern"] = "^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$"
                if path in metadata["timestamps"]:
                    field["format"] = "date-time"
                    field["pattern"] = "Z$"
        schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
        results[name + ".json"] = json.dumps(schema, sort_keys=True, indent=2) + "\n"
    declared = set(metadata["field_rules"]) | set(metadata["identities"]) | set(metadata["timestamps"])
    if declared - found:
        raise ValueError(f"unknown metadata fields: {sorted(declared - found)}")
    results["boundary.json"] = json.dumps(metadata, sort_keys=True, indent=2) + "\n"
    return results


def generate(write=False):
    metadata = json.loads((ROOT / "baml_src/boundary.json").read_text(encoding="utf-8"))
    expected_version = metadata["compiler_version"]
    cli = os.environ.get("BAML_CLI", "baml-cli")
    version = subprocess.run([cli, "--version"], check=True, capture_output=True, text=True)
    if version.stdout.strip() != f"baml-cli {expected_version}":
        raise ValueError("BAML compiler version mismatch")
    if importlib.metadata.version("baml-bridge") != expected_version:
        raise ValueError("BAML bridge version mismatch")
    with tempfile.TemporaryDirectory(prefix="jevdrill-generated-") as temp:
        target = Path(temp) / "baml_sdk"
        subprocess.run([cli, "--project", str(ROOT), "generate", "--output-dir", str(target)],
                       check=True, capture_output=True, text=True)
        sys.path.insert(0, temp)
        try:
            module = importlib.import_module("baml_sdk")
            exported = schemas(module, metadata)
            (target / "_boundary_schemas.json").write_text(json.dumps(
                {name: json.loads(value) for name, value in exported.items()},
                sort_keys=True, indent=2) + "\n", encoding="utf-8", newline="\n")
        finally:
            sys.path.remove(temp)
            for key in list(sys.modules):
                if key == "baml_sdk" or key.startswith("baml_sdk."):
                    del sys.modules[key]
        generated = {p.relative_to(target): p.read_bytes() for p in target.rglob("*")
                     if p.is_file() and "__pycache__" not in p.parts}
        destination = ROOT / "src/baml_sdk"
        stale = []
        expected_paths = set(generated)
        existing = {p.relative_to(destination) for p in destination.rglob("*")
                    if p.is_file() and "__pycache__" not in p.parts}
        if existing - expected_paths:
            raise ValueError("obsolete generated files; inspect and remove explicitly")
        actual_normalized = normalized_outputs(generated)
        existing_bytes = {p: (destination / p).read_bytes() for p in existing}
        existing_normalized = normalized_outputs(existing_bytes) if existing == expected_paths else {}
        for relative, content in generated.items():
            file = destination / relative
            if actual_normalized[relative] != existing_normalized.get(relative):
                stale.append(str(file.relative_to(ROOT)))
                if write:
                    file.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(target / relative, file)
        for relative, content in exported.items():
            file = ROOT / "schemas" / relative
            if not file.exists() or file.read_text(encoding="utf-8") != content:
                stale.append(str(file.relative_to(ROOT)))
                if write:
                    file.parent.mkdir(parents=True, exist_ok=True)
                    file.write_text(content, encoding="utf-8", newline="\n")
        if stale and not write:
            raise ValueError("stale generated outputs: " + ", ".join(stale))
        return {"passed": True, "generated_files": len(generated), "schemas": len(exported), "write": write}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    print(json.dumps(generate(args.write)))
