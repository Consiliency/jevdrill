"""Validate the vocabulary registry and render its read-only glossary.

This checks registry consistency, not vocabulary usage throughout the codebase.
"""
import argparse
import hashlib
from pathlib import Path
import re
import sys

import yaml


class UniqueKeyLoader(yaml.SafeLoader):
    pass


def mapping(loader, node):
    result = {}
    for key_node, value_node in node.value:
        key = loader.construct_object(key_node)
        if key in result:
            raise ValueError(f"duplicate YAML key: {key}")
        result[key] = loader.construct_object(value_node)
    return result


UniqueKeyLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, mapping)


def cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def render(path, repo):
    raw = path.read_bytes()
    registry = yaml.load(raw, Loader=UniqueKeyLoader)
    modules = registry["modules"]
    decisions = set(re.findall(r"^### (JD-\d+) —", (repo / registry["source"]).read_text(encoding="utf-8"), re.M))
    seen = set()
    for concept in registry["concepts"]:
        identity = concept["id"]
        if identity in seen or not re.fullmatch(r"[a-z][a-z0-9_]*", identity):
            raise ValueError(f"duplicate or invalid concept ID: {identity}")
        seen.add(identity)
        if concept["owner"] not in modules:
            raise ValueError(f"unknown owner for {identity}")
        if concept["decision"] not in decisions:
            raise ValueError(f"unknown decision for {identity}")
        if concept["identifier"] != identity:
            raise ValueError(f"identifier differs from concept ID: {identity}")
    rows = [
        "# JEV Drill vocabulary", "",
        "Generated from [vocabulary.yaml](vocabulary.yaml). Do not edit this file directly.", "",
        f"Registry SHA-256: `{hashlib.sha256(raw).hexdigest()}`", "",
        "Regenerate: `python3 scripts/render_vocabulary.py`; verify: `python3 scripts/render_vocabulary.py --check`.", "",
        "Scoped identifier and usage checks run with `scripts/lint_vocabulary.py`; import rules run with `scripts/check_import_boundaries.py`. These checks do not prove prose semantics.", "",
        "## Concepts", "",
        "| Term | Identifier | Owner | Meaning | Decision |",
        "|---|---|---|---|---|",
    ]
    for concept in registry["concepts"]:
        label = concept["term"]
        if concept.get("spelling_status") == "implementation_proposal":
            label += " (identifier proposed)"
        rows.append("| " + " | ".join(cell(value) for value in (
            label, f"`{concept['identifier']}`", f"`{concept['owner']}`",
            concept["definition"], concept["decision"],
        )) + " |")
    rows += ["", "## Modules", "", "| Module | Responsibility |", "|---|---|"]
    rows += [f"| `{name}` | {cell(description)} |" for name, description in modules.items()]
    rows += ["", "## Scope", "",
             "Rules, aliases, exemptions, and their implementation status are defined in the YAML registry.",
             "Module ownership here is the consolidation proposal; exact import rules are in the implementation proposal.", ""]
    return "\n".join(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    repo = Path(__file__).resolve().parents[1]
    source = repo / "docs/vocabulary.yaml"
    target = repo / "docs/vocabulary.md"
    expected = render(source, repo)
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != expected:
            print("Generated glossary is stale; run scripts/render_vocabulary.py", file=sys.stderr)
            return 1
    else:
        target.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
